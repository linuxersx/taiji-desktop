/* Root helper for the Taiji local SMB sharing UI.
 *
 * The Taiji frontend runs as the seat user; this helper is launched through
 * pkexec (see /usr/share/polkit-1/rules.d/50-taiji-smb.rules) and owns the
 * generated share list plus the smb.service state.
 */
#define _GNU_SOURCE
#include <ctype.h>
#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <pwd.h>
#include <sys/stat.h>
#include <sys/types.h>
#include <unistd.h>

#define SHARE_FILE "/etc/samba/taiji-shares.conf"
#define SMB_CONF "/etc/samba/smb.conf"
#define SMB_SERVICE "smb"

typedef struct {
    char name[96];
    char path[1024];
    int readonly;
} Share;

static Share shares[128];
static int share_count;

static int cmp_share(const void *a, const void *b)
{
    return strcmp(((const Share *)a)->name, ((const Share *)b)->name);
}

static int fail(const char *msg)
{
    fprintf(stderr, "%s\n", msg);
    return 1;
}

static int valid_name(const char *name)
{
    size_t n = strlen(name);
    if (n < 1 || n > 63) return 0;
    if (strcmp(name, ".") == 0 || strcmp(name, "..") == 0) return 0;
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)name[i];
        if (c >= 0x80) continue;              /* UTF-8 share names */
        if (c < 0x20) return 0;
        if (c == '[' || c == ']' || c == '/' || c == '\\') return 0;
    }
    return 1;
}

static int valid_path(const char *path)
{
    struct stat st;
    if (!path || path[0] != '/') return 0;
    if (strchr(path, '\n') || strchr(path, '\r')) return 0;
    if (strcmp(path, "/") == 0) return 0;
    if (stat(path, &st) != 0 || !S_ISDIR(st.st_mode)) return 0;
    return 1;
}

static int load_shares(void)
{
    share_count = 0;
    FILE *f = fopen(SHARE_FILE, "r");
    if (!f) return 0;
    char line[1200];
    Share cur;
    int have = 0;
    memset(&cur, 0, sizeof(cur));
    while (fgets(line, sizeof(line), f)) {
        char *s = line;
        while (*s == ' ' || *s == '\t') s++;
        if (*s == '[') {
            if (have && share_count < (int)(sizeof(shares) / sizeof(shares[0])))
                shares[share_count++] = cur;
            memset(&cur, 0, sizeof(cur));
            char *end = strchr(s, ']');
            if (end) {
                *end = '\0';
                snprintf(cur.name, sizeof(cur.name), "%s", s + 1);
                have = 1;
            } else {
                have = 0;
            }
            continue;
        }
        if (!have) continue;
        if (strncmp(s, "path", 4) == 0) {
            char *eq = strchr(s, '=');
            if (eq) {
                eq++;
                while (*eq == ' ' || *eq == '\t') eq++;
                size_t n = strcspn(eq, "\r\n");
                if (n >= sizeof(cur.path)) n = sizeof(cur.path) - 1;
                memcpy(cur.path, eq, n);
                cur.path[n] = '\0';
            }
        } else if (strncmp(s, "read only", 9) == 0) {
            char *eq = strchr(s, '=');
            if (eq) {
                eq++;
                while (*eq == ' ' || *eq == '\t') eq++;
                cur.readonly = strncasecmp(eq, "yes", 3) == 0;
            }
        }
    }
    if (have && share_count < (int)(sizeof(shares) / sizeof(shares[0])))
        shares[share_count++] = cur;
    fclose(f);
    return 0;
}

static void reload_smb(void)
{
    system("systemctl reload smb >/dev/null 2>&1");
}

static int save_shares(void)
{
    mkdir("/etc/samba", 0755);
    qsort(shares, (size_t)share_count, sizeof(shares[0]), cmp_share);
    char tmp[256];
    snprintf(tmp, sizeof(tmp), "%s.tmp", SHARE_FILE);
    FILE *f = fopen(tmp, "w");
    if (!f) return fail("无法写入共享配置");
    fprintf(f, "# Generated by Taiji. Changes here are managed from the UI.\n");
    for (int i = 0; i < share_count; i++) {
        struct stat st;
        char owner[64] = "";
        if (stat(shares[i].path, &st) == 0) {
            struct passwd pw, *res = NULL;
            char buf[4096];
            if (getpwuid_r(st.st_uid, &pw, buf, sizeof(buf), &res) == 0 && res)
                snprintf(owner, sizeof(owner), "%s", pw.pw_name);
        }
        fprintf(f, "[%s]\n", shares[i].name);
        fprintf(f, "   path = %s\n", shares[i].path);
        fprintf(f, "   browseable = yes\n");
        fprintf(f, "   guest ok = yes\n");
        if (owner[0]) fprintf(f, "   force user = %s\n", owner);
        fprintf(f, "   read only = %s\n", shares[i].readonly ? "yes" : "no");
        fprintf(f, "   create mask = 0664\n");
        fprintf(f, "   directory mask = 0775\n\n");
    }
    if (fclose(f) != 0) {
        unlink(tmp);
        return fail("无法写入共享配置");
    }
    chmod(tmp, 0644);
    if (rename(tmp, SHARE_FILE) != 0) {
        unlink(tmp);
        return fail("无法更新共享配置");
    }
    return 0;
}

static int ensure_smb_conf(void)
{
    mkdir("/etc/samba", 0755);
    struct stat st;
    if (stat(SMB_CONF, &st) != 0) {
        FILE *f = fopen(SMB_CONF, "w");
        if (!f) return fail("无法创建 smb.conf");
        fprintf(f,
                "[global]\n"
                "   workgroup = WORKGROUP\n"
                "   server role = standalone server\n"
                "   map to guest = Bad User\n"
                "   usershare allow guests = no\n"
                "   server min protocol = SMB2_02\n\n"
                "include = %s\n", SHARE_FILE);
        fclose(f);
        chmod(SMB_CONF, 0644);
        return 0;
    }
    FILE *f = fopen(SMB_CONF, "r");
    if (!f) return fail("无法读取 smb.conf");
    char line[2048];
    int included = 0;
    while (fgets(line, sizeof(line), f)) {
        if (strstr(line, "taiji-shares.conf")) { included = 1; break; }
    }
    fclose(f);
    if (included) return 0;
    f = fopen(SMB_CONF, "a");
    if (!f) return fail("无法更新 smb.conf");
    fprintf(f, "\n# Taiji managed shares\ninclude = %s\n", SHARE_FILE);
    fclose(f);
    return 0;
}

static Share *find_share(const char *name)
{
    for (int i = 0; i < share_count; i++)
        if (strcmp(shares[i].name, name) == 0) return &shares[i];
    return NULL;
}

static int op_list(void)
{
    load_shares();
    for (int i = 0; i < share_count; i++)
        printf("%s\t%s\t%d\n", shares[i].name, shares[i].path,
               shares[i].readonly);
    return 0;
}

static int op_status(void)
{
    int active = system("systemctl is-active --quiet " SMB_SERVICE) == 0;
    int installed = access("/usr/bin/smbd", X_OK) == 0;
    printf("%d %d\n", active, installed);
    return 0;
}

static int op_add(const char *name, const char *path, int readonly)
{
    if (!valid_name(name)) return fail("共享名称不合法");
    if (!valid_path(path)) return fail("共享目录不存在或不可用");
    load_shares();
    if (find_share(name)) return fail("同名共享已存在");
    if (share_count >= (int)(sizeof(shares) / sizeof(shares[0])))
        return fail("共享数量已达上限");
    Share *s = &shares[share_count++];
    snprintf(s->name, sizeof(s->name), "%s", name);
    snprintf(s->path, sizeof(s->path), "%s", path);
    s->readonly = readonly ? 1 : 0;
    if (ensure_smb_conf() != 0) return 1;
    int rc = save_shares();
    reload_smb();
    return rc;
}

static int op_set(const char *name, const char *path, int readonly)
{
    if (!valid_name(name)) return fail("共享名称不合法");
    if (!valid_path(path)) return fail("共享目录不存在或不可用");
    load_shares();
    Share *s = find_share(name);
    if (!s) return fail("共享不存在");
    snprintf(s->path, sizeof(s->path), "%s", path);
    s->readonly = readonly ? 1 : 0;
    int rc = save_shares();
    reload_smb();
    return rc;
}

static int op_remove(const char *name)
{
    load_shares();
    Share *s = find_share(name);
    if (!s) return fail("共享不存在");
    int idx = (int)(s - shares);
    memmove(&shares[idx], &shares[idx + 1],
            sizeof(shares[0]) * (size_t)(share_count - idx - 1));
    share_count--;
    int rc = save_shares();
    reload_smb();
    return rc;
}

static int run_service(const char *verb)
{
    if (ensure_smb_conf() != 0) return 1;
    char cmd[128];
    if (strcmp(verb, "enable") == 0)
        snprintf(cmd, sizeof(cmd),
                 "systemctl enable --now " SMB_SERVICE " >/dev/null 2>&1");
    else
        snprintf(cmd, sizeof(cmd),
                 "systemctl disable --now " SMB_SERVICE " >/dev/null 2>&1");
    if (system(cmd) != 0) return fail("无法切换共享服务状态");
    return 0;
}

int main(int argc, char **argv)
{
    if (geteuid() != 0) return fail("需要管理员权限");
    if (argc < 2) return fail("用法: taiji-smb-helper <list|add|set|remove|enable|disable|status>");

    const char *op = argv[1];
    if (strcmp(op, "list") == 0) return op_list();
    if (strcmp(op, "status") == 0) return op_status();
    if (strcmp(op, "enable") == 0) return run_service("enable");
    if (strcmp(op, "disable") == 0) return run_service("disable");
    if (strcmp(op, "add") == 0) {
        if (argc < 5) return fail("参数不足");
        return op_add(argv[2], argv[3], atoi(argv[4]));
    }
    if (strcmp(op, "set") == 0) {
        if (argc < 5) return fail("参数不足");
        return op_set(argv[2], argv[3], atoi(argv[4]));
    }
    if (strcmp(op, "remove") == 0) {
        if (argc < 3) return fail("参数不足");
        return op_remove(argv[2]);
    }
    return fail("未知操作");
}
