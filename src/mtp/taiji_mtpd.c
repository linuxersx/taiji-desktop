/*
 * taiji-mtpd —— 太极的 USB MTP 响应器封装。
 *
 * 职责：
 *   1. 解析 armdeck-adbd 传入的 FunctionFS 路径
 *   2. 找「当前活动用户」的主目录（也可用 --user 指定）
 *   3. 生成 uMTP-Responder 的配置（只读/读写来自 /etc/armdeck-usb-mtp.mode）
 *   4. exec 真正的响应器 taiji-mtprd（vendored uMTP-Responder）
 *
 * MTP 协议实现来自 third_party/umtp-responder（GPLv3），它是独立可执行文件，
 * 本封装不含任何 MTP 协议代码。
 */
#define _GNU_SOURCE
#include <dirent.h>
#include <errno.h>
#include <fcntl.h>
#include <pwd.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <sys/types.h>
#include <unistd.h>

#define DEFAULT_FFS   "/dev/usb-ffs/mtp"
#define DEFAULT_CONF  "/run/taiji-mtpd.conf"
#define MODE_FILE     "/etc/armdeck-usb-mtp.mode"
#define CORE_BIN      "/usr/libexec/taiji/taiji-mtprd"
#define BATTERY_CAP   "/sys/class/power_supply/battery/capacity"

static void usage(const char *a0)
{
	fprintf(stderr,
		"usage: %s [--ffs DIR] [--user NAME] [--mode ro|rw] [--conf PATH]\n",
		a0);
}

/* 读取只读/读写模式；默认读写 */
static const char *read_mode(void)
{
	static char buf[16];
	FILE *f = fopen(MODE_FILE, "r");
	size_t n;

	if (!f)
		return "rw";
	memset(buf, 0, sizeof(buf));
	n = fread(buf, 1, sizeof(buf) - 1, f);
	fclose(f);
	if (n == 0)
		return "rw";
	/* 去掉换行 */
	buf[strcspn(buf, "\r\n")] = '\0';
	if (!strcmp(buf, "ro"))
		return "ro";
	return "rw";
}

static int uid_from_dirname(const char *name)
{
	char *end = NULL;
	long v;

	if (!name || !*name)
		return -1;
	for (const char *p = name; *p; p++)
		if (*p < '0' || *p > '9')
			return -1;
	v = strtol(name, &end, 10);
	if (!end || *end || v < 1000 || v > 60000)
		return -1;
	return (int)v;
}

static int user_from_uid(int uid, char *user, size_t un, char *home, size_t hn)
{
	struct passwd pwd, *res = NULL;
	char buf[4096];

	if (getpwuid_r((uid_t)uid, &pwd, buf, sizeof(buf), &res) != 0 || !res)
		return -1;
	if (!res->pw_dir || !*res->pw_dir)
		return -1;
	snprintf(user, un, "%s", res->pw_name ? res->pw_name : "");
	snprintf(home, hn, "%s", res->pw_dir);
	return 0;
}

/* 找当前有会话的用户：取 /run/user/<uid> 里最小的 uid（>=1000）。 */
static int find_active_user(char *user, size_t un, char *home, size_t hn)
{
	DIR *d = opendir("/run/user");
	struct dirent *ent;
	int best = -1;

	if (d) {
		while ((ent = readdir(d)) != NULL) {
			int uid = uid_from_dirname(ent->d_name);

			if (uid < 0)
				continue;
			if (best < 0 || uid < best)
				best = uid;
		}
		closedir(d);
	}
	if (best >= 0 && user_from_uid(best, user, un, home, hn) == 0)
		return 0;

	/* 兜底：/home 下第一个普通用户目录 */
	d = opendir("/home");
	if (!d)
		return -1;
	while ((ent = readdir(d)) != NULL) {
		char path[4096];
		struct stat st;

		if (ent->d_name[0] == '.')
			continue;
		snprintf(path, sizeof(path), "/home/%s", ent->d_name);
		if (stat(path, &st) != 0 || !S_ISDIR(st.st_mode))
			continue;
		if (st.st_uid < 1000)
			continue;
		if (user_from_uid((int)st.st_uid, user, un, home, hn) == 0) {
			closedir(d);
			return 0;
		}
	}
	closedir(d);
	return -1;
}

static void write_config(const char *path, const char *ffs, const char *user,
			 const char *home, const char *mode, int uid, int gid)
{
	FILE *f = fopen(path, "w");
	char cap[32] = "";

	if (!f) {
		fprintf(stderr, "taiji-mtpd: cannot write %s: %s\n", path,
			strerror(errno));
		exit(1);
	}
	fchmod(fileno(f), 0600);

	/* 电池电量：有就报，没有就不报 */
	if (access(BATTERY_CAP, R_OK) == 0) {
		FILE *b = fopen(BATTERY_CAP, "r");

		if (b) {
			if (fgets(cap, sizeof(cap), b))
				cap[strcspn(cap, "\r\n")] = '\0';
			fclose(b);
		}
	}

	fprintf(f, "# generated by taiji-mtpd, do not edit\n");
	fprintf(f, "loop_on_disconnect 1\n");
	fprintf(f, "\n");
	fprintf(f, "usb_functionfs_mode 0x1\n");
	fprintf(f, "usb_dev_path   \"%s/ep0\"\n", ffs);
	fprintf(f, "usb_epin_path  \"%s/ep1\"\n", ffs);
	fprintf(f, "usb_epout_path \"%s/ep2\"\n", ffs);
	fprintf(f, "usb_epint_path \"%s/ep3\"\n", ffs);
	fprintf(f, "usb_max_packet_size 0x200\n");
	fprintf(f, "\n");
	fprintf(f, "interface \"MTP\"\n");
	fprintf(f, "manufacturer \"Taiji\"\n");
	fprintf(f, "product \"Taiji USB Storage\"\n");
	fprintf(f, "serial \"taiji-%s\"\n", user);
	fprintf(f, "mtp_extensions \"microsoft.com: 1.0; android.com: 1.0;\"\n");
	fprintf(f, "perceived_device_type 0x5\n");
	fprintf(f, "show_hidden_files 0x0\n");
	fprintf(f, "umask 022\n");
	/* 主机上传的文件归当前用户，而不是 root */
	fprintf(f, "default_uid %d\n", uid);
	fprintf(f, "default_gid %d\n", gid);
	if (cap[0])
		fprintf(f, "battery_capacity \"%s\"\n", BATTERY_CAP);
	fprintf(f, "\n");
	fprintf(f, "# 当前登录用户的主目录；%s\n", mode);
	fprintf(f, "storage \"%s\" \"%s\" \"%s\"\n", home, user, mode);
	fclose(f);
}

static const char *find_core(const char *argv0)
{
	static char path[4096];

	if (access(CORE_BIN, X_OK) == 0)
		return CORE_BIN;

	/* 和自身放一起（开发构建目录） */
	const char *slash = strrchr(argv0, '/');

	if (slash) {
		size_t n = (size_t)(slash - argv0);

		snprintf(path, sizeof(path), "%.*s/taiji-mtprd", (int)n, argv0);
		if (access(path, X_OK) == 0)
			return path;
	}
	return NULL;
}

int main(int argc, char **argv)
{
	const char *ffs = DEFAULT_FFS;
	const char *conf = DEFAULT_CONF;
	const char *forced_user = NULL;
	const char *forced_mode = NULL;
	const char *mode;
	const char *core;
	char user[128] = "";
	char home[4096] = "";

	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--ffs") && i + 1 < argc)
			ffs = argv[++i];
		else if (!strcmp(argv[i], "--user") && i + 1 < argc)
			forced_user = argv[++i];
		else if (!strcmp(argv[i], "--mode") && i + 1 < argc)
			forced_mode = argv[++i];
		else if (!strcmp(argv[i], "--conf") && i + 1 < argc)
			conf = argv[++i];
		else if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) {
			usage(argv[0]);
			return 0;
		} else {
			usage(argv[0]);
			return 2;
		}
	}

	if (forced_user) {
		struct passwd *pw = getpwnam(forced_user);

		if (!pw || !pw->pw_dir) {
			fprintf(stderr, "taiji-mtpd: unknown user %s\n",
				forced_user);
			return 1;
		}
		snprintf(user, sizeof(user), "%s", pw->pw_name);
		snprintf(home, sizeof(home), "%s", pw->pw_dir);
	} else if (find_active_user(user, sizeof(user), home, sizeof(home)) != 0) {
		fprintf(stderr, "taiji-mtpd: no active user found\n");
		return 1;
	}

	mode = forced_mode ? forced_mode : read_mode();
	if (strcmp(mode, "ro") != 0 && strcmp(mode, "rw") != 0) {
		fprintf(stderr, "taiji-mtpd: invalid mode %s\n", mode);
		return 1;
	}

	if (access(home, R_OK) != 0) {
		fprintf(stderr, "taiji-mtpd: home %s not accessible\n", home);
		return 1;
	}

	fprintf(stderr, "taiji-mtpd: ffs=%s user=%s home=%s mode=%s\n",
		ffs, user, home, mode);
	{
		struct passwd *pw = getpwnam(user);

		if (!pw) {
			fprintf(stderr, "taiji-mtpd: user %s vanished\n", user);
			return 1;
		}
		write_config(conf, ffs, user, home, mode,
			     (int)pw->pw_uid, (int)pw->pw_gid);
	}

	core = find_core(argv[0]);
	if (!core) {
		fprintf(stderr, "taiji-mtpd: taiji-mtprd not found\n");
		return 1;
	}

	execl(core, "taiji-mtprd", "-conf", conf, (char *)NULL);
	fprintf(stderr, "taiji-mtpd: exec %s failed: %s\n", core,
		strerror(errno));
	return 1;
}
